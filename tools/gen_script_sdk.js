// gen_script_sdk.js -- embed the script SDK's Lua libraries (src/sdk/lua/*.lua) in the backend.
//   node tools/gen_script_sdk.js           write src/backend/script/script_sdk_lua.c
//   node tools/gen_script_sdk.js --check   exit 1 when that file is not what the sources give
// The libraries ship inside the DLL, so a mod requires them by name and carries no copy.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'src', 'sdk', 'lua');
const out = path.join(root, 'src', 'backend', 'script', 'script_sdk_lua.c');
const names = fs.readdirSync(dir).filter((f) => f.endsWith('.lua')).sort();
let c = '/* script_sdk_lua.c -- GENERATED by tools/gen_script_sdk.js from src/sdk/lua/*.lua; do not edit.\n' +
        ' * The script SDK\'s libraries as bytes (script_sdk.h). */\n#include "script_sdk.h"\n\n';
names.forEach((file, i) => {
  const bytes = fs.readFileSync(path.join(dir, file)).toString('utf8').replace(/\r\n/g, '\n');
  const b = Buffer.from(bytes, 'utf8');
  c += `static const unsigned char k_lib_${i}[] = {`;
  for (let k = 0; k < b.length; k++) c += (k % 24 === 0 ? '\n    ' : '') + b[k] + ',';
  c += '\n};\n\n';
});
c += 'const sh_script_sdk_lib SH_SCRIPT_SDK_LIBS[] = {\n';
names.forEach((file, i) => { c += `    { "${file.slice(0, -4)}", (const char *)k_lib_${i}, sizeof k_lib_${i} },\n`; });
c += '    { 0, 0, 0 }\n};\n';
if (process.argv.includes('--check')) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== c) { console.error('script_sdk_lua.c is out of date: run node tools/gen_script_sdk.js'); process.exit(1); }
  console.log(`script_sdk_lua.c matches ${names.length} librar${names.length === 1 ? 'y' : 'ies'}`);
} else {
  fs.writeFileSync(out, c);
  console.log(`wrote ${path.relative(root, out)} (${names.length} libraries)`);
}
