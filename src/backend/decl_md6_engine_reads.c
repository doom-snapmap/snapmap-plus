typedef struct der_witness {uintptr_t at;size_t size;unsigned char bytes[8];} der_witness;
typedef struct der_probe {
    sh_resource_default_read_receipt *r;const sh_resource_default_read_input *in;
    const der_profile *profile;der_witness witnesses[32];size_t count;uintptr_t epoch_at;
} der_probe;
static int der_fail(der_probe *p,sh_resource_default_read_reason why,uintptr_t at)
{p->r->reason=why;p->r->offending_address=at;return 0;}
static int der_read(der_probe *p,uintptr_t at,size_t offset,void *out,size_t size,int witness)
{
    if(offset>UINTPTR_MAX-at || (size && (!at || size>UINTPTR_MAX-(at+offset))))
        return der_fail(p,SH_DEFAULT_READ_BOUNDS,at);
    at+=offset;
    if(p->r->work==SIZE_MAX || (p->in->work_limit && p->r->work>=p->in->work_limit))
        return der_fail(p,SH_DEFAULT_READ_BUDGET,at);
    p->r->work++;
    if(!p->in->read(p->in->read_context,at,out,size))return der_fail(p,SH_DEFAULT_READ_MEMORY,at);
    if(witness) {
        if(size>8 || p->count==sizeof p->witnesses/sizeof *p->witnesses)
            return der_fail(p,SH_DEFAULT_READ_BOUNDS,at);
        der_witness *w=p->witnesses+p->count++;w->at=at;w->size=size;memcpy(w->bytes,out,size);
    }
    return 1;
}
static int der_data(der_probe *p,uint32_t rva,void *out,size_t size)
{
    if(rva>p->in->image_size || size>p->in->image_size-rva)
        return der_fail(p,SH_DEFAULT_READ_IMAGE,p->in->image_base);
    return der_read(p,p->in->image_base,rva,out,size,1);
}
static int der_bind(der_probe *p,uint32_t at,uint32_t value)
{
    uintptr_t actual;if(!der_data(p,at,&actual,8))return 0;
    return actual==p->in->image_base+value || der_fail(p,SH_DEFAULT_READ_CALLBACK,p->in->image_base+at);
}
static int der_pin_check(der_probe *p,const der_pin *pin)
{
    sh_native_pin_hash hash;unsigned char digest[32];
    sh_native_pin_hash_init(&hash);
    unsigned char bytes[64];
    if(pin->rva>p->in->image_size || pin->length>p->in->image_size-pin->rva)
        return der_fail(p,SH_DEFAULT_READ_IMAGE,p->in->image_base);
    for(size_t offset=0;offset<pin->length;) {
        size_t n=pin->length-offset;if(n>sizeof bytes)n=sizeof bytes;
        uintptr_t at=p->in->image_base+pin->rva;
        if(!der_read(p,at,offset,bytes,n,0))return 0;
        sh_native_pin_hash_update(&hash,bytes,n);
        offset+=n;
    }
    sh_native_pin_hash_finish(&hash,digest);
    return !memcmp(digest,pin->hash,sizeof digest) || der_fail(p,SH_DEFAULT_READ_PIN,p->in->image_base+pin->rva);
}
static uint64_t der_ror(uint64_t value,unsigned bits)
{bits&=63;return bits?(value>>bits)|(value<<(64-bits)):value;}
static uintptr_t der_decode(uint64_t value,uint64_t cookie)
{return (uintptr_t)der_ror(value^cookie,(unsigned)cookie&63);}
static int der_exit_storage(der_probe *p,uint64_t cookie)
{
    uint64_t encoded[3];const der_profile *b=p->profile;uint32_t table=b->exit_table;
    if(!der_data(p,table,&encoded[0],8))return 0;
    if(der_decode(encoded[0],cookie)==UINTPTR_MAX)table=b->exit_fallback;
    for(unsigned i=0;i<3;i++)if(!der_data(p,table+i*8,encoded+i,8))return 0;
    uintptr_t begin=der_decode(encoded[0],cookie),end=der_decode(encoded[1],cookie),capacity=der_decode(encoded[2],cookie);
    if(begin>end || end>capacity || (begin&7) || ((end-begin)&7) || ((capacity-begin)&7) ||
       capacity-begin>INT64_MAX || (!begin && capacity))return der_fail(p,SH_DEFAULT_READ_OWNERSHIP,p->in->image_base+table);
    size_t count=(capacity-begin)/8;
    /* Both preferred and +4 fallback registration growth must fit native
     * _recalloc_base's limit. Callback slot bytes are opaque and never called. */
    size_t grow=count>0x200?0x200:count;
    if(count>(SIZE_MAX-0x20)/8 || grow>(SIZE_MAX-0x20)/8-count || count>(SIZE_MAX-0x20)/8-4)
        return der_fail(p,SH_DEFAULT_READ_BOUNDS,begin);
    unsigned char bytes[64];
    for(size_t offset=0;offset<capacity-begin;) {
        size_t n=capacity-begin-offset;if(n>sizeof bytes)n=sizeof bytes;
        if(!der_read(p,begin,offset,bytes,n,0))return 0;offset+=n;
    }
    return 1;
}
static int der_tls(der_probe *p,int *epoch)
{
    uintptr_t tls_array=SH_DECL_ENGINE_TLS_ARRAY(),tls_block;uint32_t tls_index;
    if(!der_data(p,p->profile->tls_index,&tls_index,4))return 0;
    if(!tls_array)return der_fail(p,SH_DEFAULT_READ_MEMORY,tls_array);
    if(!der_read(p,tls_array,(size_t)tls_index*8,&tls_block,8,1) ||
       !der_read(p,tls_block,4,epoch,4,1))return 0;
    p->epoch_at=tls_block+4;return 1;
}
static int der_cold(der_probe *p)
{
    const der_profile *b=p->profile;uintptr_t sys;uint64_t cookie,event,wait,notify;
    if(!der_data(p,b->sys,&sys,8))return 0;
    /* Sys getter's nonnull branch has no call at all. The separate Sys-null
     * Steam constructor is outside the native compiler's Sys-ready route. */
    if(!sys)return der_fail(p,SH_DEFAULT_READ_CALLBACK,p->in->image_base+b->sys);
    if(!der_data(p,b->cookie,&cookie,8) || !der_data(p,b->event,&event,8))return 0;
    if(!event) {
        if(!der_data(p,b->wait,&wait,8) || !der_data(p,b->notify,&notify,8))return 0;
        uintptr_t expected_wait=SH_DECL_ENGINE_OS_EXPORT("SleepConditionVariableCS");
        uintptr_t expected_notify=SH_DECL_ENGINE_OS_EXPORT("WakeAllConditionVariable");
        if(!expected_wait || !expected_notify || der_decode(wait,cookie)!=expected_wait || der_decode(notify,cookie)!=expected_notify)
            return der_fail(p,SH_DEFAULT_READ_CALLBACK,p->in->image_base+b->wait);
    }
    return sh_decl_default_allocator_read_check(p->r,p->in) &&
        sh_decl_default_crt_allocation_read_check(p->r,p->in) && der_exit_storage(p,cookie);
}
int sh_decl_engine_read_check(sh_resource_default_read_receipt *r,const sh_resource_default_read_input *in,unsigned methods)
{
    der_probe p={0};p.r=r;p.in=in;int guard,epoch;
    if(!r || !in || r->state!=1 || r->complete || r->reason!=SH_DEFAULT_READ_UNSUPPORTED)return 0;
    if(in->renderer<0 || in->renderer>1 || !in->pinned_image || !in->read || !in->image_base ||
       !in->image_size || in->image_size>UINTPTR_MAX-in->image_base || !methods || (methods&~3u) ||
       r->invocation.image_base!=in->image_base || r->invocation.image_size!=in->image_size ||
       r->invocation.renderer!=in->renderer || r->invocation.pinned_image!=in->pinned_image ||
       r->invocation.resource!=in->resource || r->invocation.default_callback!=in->default_callback ||
       r->invocation.read!=in->read || r->invocation.read_context!=in->read_context || r->invocation.work_limit!=in->work_limit)
        return der_fail(&p,SH_DEFAULT_READ_INPUT,in->resource);
    p.profile=der_profiles+in->renderer;const der_profile *b=p.profile;
    r->routine=SH_DEFAULT_READ_ROUTINE_DECLARATION;
    if(!der_bind(&p,b->common_holder,b->common) || !der_bind(&p,b->common,b->common_table) ||
       !der_data(&p,b->guard,&guard,4))return 0;
    if((methods&1) && (!der_bind(&p,b->common_table+0x240,b->pins[0].rva) || !der_bind(&p,b->engine_table+0x80,b->pins[3].rva)))return 0;
    if((methods&2) && (!der_bind(&p,b->common_table+0x250,b->pins[1].rva) || !der_bind(&p,b->engine_table+0x90,b->pins[4].rva)))return 0;
    int cold=guard==0 || guard==-1;
    /* The getter reads TLS even when the singleton is already initialized.
     * A stale initialized epoch enters header, whose initialized branch only
     * locks, copies the global scalar epoch into TLS and unlocks. The complete
     * header is pinned below; it does not reach wait/footer/constructor work. */
    if(!der_tls(&p,&epoch))return 0;
    if(cold && epoch>=guard)return der_fail(&p,SH_DEFAULT_READ_OWNERSHIP,p.epoch_at);
    for(size_t i=0;i<b->pin_count;i++) {
        const der_pin *pin=b->pins+i;
        if((pin->flags==4 && !cold) || (pin->flags==1 && !(methods&1)) || (pin->flags==2 && !(methods&2)))continue;
        if(!der_pin_check(&p,pin))return 0;
    }
    if(cold) {if(!der_cold(&p))return 0;}
    else if(!der_bind(&p,b->engine,b->engine_table) ||
            ((methods&2) && !der_bind(&p,b->engine+0x1a0,b->member_table)))return 0;
    for(size_t i=0;i<p.count;i++) {
        unsigned char actual[8];der_witness *w=p.witnesses+i;
        if(!der_read(&p,w->at,0,actual,w->size,0))return 0;
        if(memcmp(actual,w->bytes,w->size))return der_fail(&p,SH_DEFAULT_READ_INVOCATION,w->at);
    }
    return 1;
}
