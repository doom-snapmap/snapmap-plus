static int mrg_string_destroy(mrg_probe *p,uintptr_t at)
{
    uintptr_t data;uint32_t flags;int length;
    if(!mrg_read(p,at,8,&length,4) || !mrg_read(p,at,16,&data,8) || !mrg_read(p,at,24,&flags,4))return 0;
    if(length<0 || (length && !data) || ((flags&0x3fffffff) && (uint32_t)length>=(flags&0x3fffffff)))
        return mrg_fail(p,SH_DEFAULT_READ_OWNERSHIP,at);
    return !(flags&0x40000000) || mrg_span_add(p,data,1,1);
}
static int mrg_old_setups(mrg_probe *p)
{
    mrg_list setups,components,attached;
    if(!mrg_list_read(p,p->in->resource+0x308,8,&setups) ||
       !mrg_span_add(p,setups.data,(size_t)setups.capacity*8,0) ||
       !mrg_list_read(p,p->in->resource+0x320,8,&attached) ||
       !mrg_span_add(p,attached.data,(size_t)attached.capacity*8,0))return 0;
    /* Clearing the setup list destroys COUNT pointees for every outer flag;
     * it does not free the outer pointer array or retained instance objects. */
    for(int i=0;i<setups.count;i++) {
        uintptr_t setup;if(!mrg_read(p,setups.data,(size_t)i*8,&setup,8))return 0;
        if(!setup)continue;
        if(!mrg_span_add(p,setup,0x50,1) || !mrg_list_read(p,setup+0x38,8,&components))return 0;
        if(components.data && !mrg_span_add(p,components.data,(size_t)components.capacity*8,mrg_owned(components.flags)))return 0;
        for(int k=0;k<components.count;k++) {
            uintptr_t component,table,callback;
            if(!mrg_read(p,components.data,(size_t)k*8,&component,8))return 0;
            if(!component)continue;
            if(!mrg_read(p,component,0,&table,8) || !mrg_read(p,table,0,&callback,8))return 0;
            unsigned c;for(c=0;c<7;c++)if(callback==p->in->image_base+p->profile->destructors[c])break;
            if(c==7)return mrg_fail(p,SH_DEFAULT_READ_CALLBACK,callback);
            static const size_t sizes[]={0x50,0xc0,0x68,0x58,0x38,8,0x28};
            if(!mrg_span_add(p,component,sizes[c],1))return 0;
        }
        if(!mrg_string_destroy(p,setup))return 0;
    }
    return 1;
}
static int mrg_envelope(mrg_probe *p)
{
    sh_resource_default_read_receipt *r=p->r;const sh_resource_default_read_input *in=p->in;
    if(!r || !in || r->state!=1 || r->complete || r->reason!=SH_DEFAULT_READ_UNSUPPORTED)return 0;
    if(in->renderer<0 || in->renderer>1 || !in->pinned_image || !in->read || !in->resource ||
       !in->default_callback || !in->image_base || !in->image_size || in->image_size>UINTPTR_MAX-in->image_base ||
       r->invocation.image_base!=in->image_base || r->invocation.image_size!=in->image_size ||
       r->invocation.renderer!=in->renderer || r->invocation.pinned_image!=in->pinned_image ||
       r->invocation.resource!=in->resource || r->invocation.default_callback!=in->default_callback ||
       r->invocation.read!=in->read || r->invocation.read_context!=in->read_context || r->invocation.work_limit!=in->work_limit)
        return mrg_fail(p,SH_DEFAULT_READ_INPUT,in->resource);
    p->profile=mrg_profiles+in->renderer;r->routine=SH_DEFAULT_READ_ROUTINE_DECLARATION;
    uintptr_t table,callback;
    if(!mrg_extent(p,in->resource,0x340) || !mrg_read(p,in->resource,0,&table,8) ||
       !mrg_read(p,table,0x50,&callback,8))return 0;
    if(callback!=in->default_callback)return mrg_fail(p,SH_DEFAULT_READ_CALLBACK,callback);
    if(!mrg_read(p,table,0xa0,&callback,8))return 0;
    if(callback!=in->image_base+p->profile->release)return mrg_fail(p,SH_DEFAULT_READ_CALLBACK,callback);
    if(!sh_decl_default_allocator_read_check(r,in) || !sh_decl_default_crt_allocation_read_check(r,in))return 0;
    p->code=1;
    for(size_t i=0;i<p->profile->pin_count;i++)if(!mrg_pin_check(p,p->profile->pins+i))return 0;
    p->code=0;
    return mrg_old_setups(p);
}
static int mrg_component(mrg_probe *p,uintptr_t component,int *bytes,int *active,uintptr_t *type,int *indices)
{
    uintptr_t table,callback,index_data;int type_count,value,offset,number;
    *active=0;*indices=0;
    if(!component)return mrg_fail(p,SH_DEFAULT_READ_OWNERSHIP,component);
    if(!mrg_span_add(p,component,0x28,0) || !mrg_read(p,component,0,&table,8))return 0;
    const unsigned slots[]={0x10,0x48},getter_indices[]={1,4};
    /* Exact getter/validator implementations read scalar metadata, not a
     * registry or name. Base abstract Init is purecall and is never blessed. */
    for(unsigned i=0;i<2;i++) {
        if(!mrg_read(p,table,slots[i],&callback,8))return 0;
        if(callback!=p->in->image_base+p->profile->getters[getter_indices[i]])return mrg_fail(p,SH_DEFAULT_READ_CALLBACK,callback);
    }
    if(!mrg_read(p,component,0x18,bytes,4))return 0;
    if(*bytes<0)return mrg_fail(p,SH_DEFAULT_READ_BOUNDS,component);
    if(!mrg_read(p,component,8,type,8))return 0;
    if(!*type)return 1; /* Validator returns false before indices/Init. */
    if(!mrg_span_add(p,*type,0x1c,0) || !mrg_read(p,*type,0x18,&type_count,4))return 0;
    if(type_count<0)return mrg_fail(p,SH_DEFAULT_READ_BOUNDS,*type);
    if(!mrg_read(p,component,0x10,&index_data,8))return 0;
    if((size_t)type_count>SIZE_MAX/4 || !mrg_extent(p,index_data,(size_t)type_count*4) ||
       !mrg_span_add(p,index_data,(size_t)type_count*4,0))return 0;
    for(int k=0;k<type_count;k++) {
        if(!mrg_read(p,index_data,(size_t)k*4,&value,4))return 0;
        if(value<0)return 1; /* Native validator stops at this exact index. */
    }
    if(!mrg_read(p,table,0x50,&callback,8))return 0;
    unsigned c;for(c=0;c<5;c++)if(callback==p->in->image_base+p->profile->initializers[c])break;
    if(c==5)return mrg_fail(p,SH_DEFAULT_READ_CALLBACK,callback);
    for(unsigned i=2;i<4;i++) {
        if(!mrg_read(p,table,i==2?0x18:0x20,&callback,8))return 0;
        if(callback!=p->in->image_base+p->profile->getters[i])return mrg_fail(p,SH_DEFAULT_READ_CALLBACK,callback);
    }
    static const size_t sizes[]={0x50,0xc0,0x68,0x58,0x38};
    static const int strides[]={0x3c,0xcc,0x84,0x70,0x2c};
    if(*bytes<strides[c])return mrg_fail(p,SH_DEFAULT_READ_BOUNDS,component);
    if(!mrg_span_add(p,component,sizes[c],0) || !mrg_blob(p,component+0x28,sizes[c]-0x28))return 0;
    if(!mrg_read(p,component,0x1c,&offset,4) || !mrg_read(p,component,0x20,&number,4))return 0;
    if(offset<0 || number<0 || offset>*bytes || number>(*bytes-offset)/4)
        return mrg_fail(p,SH_DEFAULT_READ_BOUNDS,component);
    *active=1;*indices=number;return 1;
}
static int mrg_group_read(mrg_probe *p,uintptr_t setup,mrg_group *group)
{
    mrg_list components;uintptr_t last_type=0,last_component=0;int have_last=0,metadata[2];
    group->setup=setup;group->bytes=group->groups=group->indices=0;
    if(!mrg_span_add(p,setup,0x50,0) || !mrg_read(p,setup,0x30,metadata,sizeof metadata) || !mrg_list_read(p,setup+0x38,8,&components) ||
       !mrg_span_add(p,components.data,(size_t)components.capacity*8,0))return 0;
    group->components=components.count;
    for(int i=0;i<components.count;i++) {
        uintptr_t component,type;int bytes,active,indices;
        if(!mrg_read(p,components.data,(size_t)i*8,&component,8) ||
           !mrg_component(p,component,&bytes,&active,&type,&indices))return 0;
        if(bytes>INT32_MAX-group->bytes)return mrg_fail(p,SH_DEFAULT_READ_BOUNDS,component);
        group->bytes+=bytes;
        if(active) {
            uintptr_t type_key=0,last_key=0;
            if(have_last) {
                uintptr_t checked[]={last_component,component};
                for(unsigned k=0;k<2;k++) {
                    uintptr_t table,callback;
                    if(!mrg_read(p,checked[k],0,&table,8) || !mrg_read(p,table,8,&callback,8))return 0;
                    if(callback!=p->in->image_base+p->profile->getters[0])return mrg_fail(p,SH_DEFAULT_READ_CALLBACK,callback);
                }
                if(!mrg_read(p,type,0,&type_key,8) || !mrg_read(p,last_type,0,&last_key,8))return 0;
            }
            if(!have_last || type_key!=last_key)group->groups++;
            last_type=type;last_component=component;have_last=1;
            if(indices>INT32_MAX-group->indices)return mrg_fail(p,SH_DEFAULT_READ_BOUNDS,component);
            group->indices+=indices;
        }
    }
    return 1;
}
static int mrg_old_record(mrg_probe *p,uintptr_t record,int destroyed)
{
    const size_t strides[]={0x18,0x18,4,1};
    for(unsigned i=0;i<4;i++) {
        mrg_list list;if(!mrg_list_read(p,record+i*0x18,strides[i],&list))return 0;
        /* Deep-copy constructors copy COUNT values (capacity only sizes the
         * allocation); no copied component pointer is called or chased. */
        if(!mrg_blob(p,list.data,(size_t)list.count*strides[i]))return 0;
        if(!mrg_span_add(p,list.data,(size_t)list.capacity*strides[i],destroyed && mrg_owned(list.flags)))return 0;
    }
    return 1;
}
static int mrg_numeric_resize(mrg_probe *p,uintptr_t header,int wanted,size_t stride)
{
    mrg_list list;if(!mrg_list_read(p,header,stride,&list))return 0;
    if(wanted<=list.capacity)return mrg_span_add(p,list.data,(size_t)list.capacity*stride,0);
    /* Positive growth is available only for owned flag0 or copying flag2.
     * Other flags with insufficient capacity would fail and native callers
     * could overrun storage; that malformed shape cannot qualify. */
    if(list.flags!=0 && list.flags!=2)return mrg_fail(p,SH_DEFAULT_READ_OWNERSHIP,header);
    size_t copied=list.flags==2?(size_t)list.count:(size_t)list.capacity;
    if(!mrg_blob(p,list.data,copied*stride))return 0;
    return mrg_span_add(p,list.data,(size_t)list.capacity*stride,list.flags==0);
}
static int mrg_attached(mrg_probe *p,const mrg_group *groups,int group_count)
{
    mrg_list attached;if(!mrg_list_read(p,p->in->resource+0x320,8,&attached))return 0;
    for(int i=0;i<attached.count;i++) {
        uintptr_t instance;mrg_list rows;
        if(!mrg_read(p,attached.data,(size_t)i*8,&instance,8))return 0;
        if(!instance)return mrg_fail(p,SH_DEFAULT_READ_OWNERSHIP,instance);
        if(!mrg_span_add(p,instance,0x18,0) || !mrg_list_read(p,instance,0x70,&rows))return 0;
        if(rows.capacity<group_count) {
            if(rows.flags!=0 && rows.flags!=2)return mrg_fail(p,SH_DEFAULT_READ_OWNERSHIP,instance);
            int count=rows.flags==2?rows.count:rows.capacity;
            if(!mrg_span_add(p,rows.data,(size_t)rows.capacity*0x70,rows.flags==0))return 0;
            for(int j=0;j<count;j++)if(!mrg_old_record(p,rows.data+(size_t)j*0x70,1))return 0;
            /* New capacity is fully constructed by the pinned allocator
             * helper; its four child headers start empty, then grow through
             * the same already qualified numerical resizers. */
        } else {
            if(!mrg_span_add(p,rows.data,(size_t)rows.capacity*0x70,0))return 0;
            for(int j=0;j<group_count;j++) {
                uintptr_t row=rows.data+(size_t)j*0x70;
                if(!mrg_numeric_resize(p,row,groups[j].components,0x18) ||
                   !mrg_numeric_resize(p,row+0x48,groups[j].bytes,1))return 0;
                if(groups[j].components &&
                   (!mrg_numeric_resize(p,row+0x18,groups[j].groups,0x18) ||
                    !mrg_numeric_resize(p,row+0x30,groups[j].indices,4)))return 0;
            }
        }
    }
    return 1;
}
int sh_decl_md6_rig_read_check(sh_resource_default_read_receipt *r,const sh_resource_default_read_input *in)
{
    mrg_probe p={0};p.r=r;p.in=in;int result=mrg_envelope(&p) && mrg_stable(&p);
    free(p.spans);free(p.witnesses);return result;
}
int sh_decl_md6_rig_bound_read_check(sh_resource_default_read_receipt *r,const sh_resource_default_read_input *in,
    uintptr_t actual_model,uintptr_t actual_skeleton)
{
    mrg_probe p={0};p.r=r;p.in=in;int result=0;uintptr_t model,skeleton=0,hybrid;
    if(!mrg_envelope(&p))goto done;
    if(!mrg_read(&p,in->resource,0x60,&model,8))goto done;
    if(model!=actual_model) {mrg_fail(&p,SH_DEFAULT_READ_INVOCATION,model);goto done;}
    if(model && (!mrg_span_add(&p,model,0x140,0) || !mrg_read(&p,model,0x138,&skeleton,8)))goto done;
    if(skeleton!=actual_skeleton) {mrg_fail(&p,SH_DEFAULT_READ_INVOCATION,skeleton);goto done;}
    if(skeleton) {
        if(!mrg_span_add(&p,skeleton,0x58,0) || !mrg_read(&p,skeleton,0x50,&hybrid,8))goto done;
    } else if(!mrg_read(&p,in->resource,0x338,&hybrid,8))goto done;
    mrg_group groups[3];int count=0;
    if(hybrid) {
        if(!mrg_span_add(&p,hybrid,0x198,0))goto done;
        const size_t offsets[]={0xa8,0xf8,0x148};
        for(int i=0;i<3;i++)if(!mrg_group_read(&p,hybrid+offsets[i],groups+i))goto done;
        /* Native orders the three embedded groups by scalar priority+30,
         * preserving equal priorities. Attached row j uses this exact order. */
        for(int i=1;i<3;i++) {
            int priority;if(!mrg_read(&p,groups[i].setup,0x30,&priority,4))goto done;
            mrg_group value=groups[i];int j=i;
            while(j>0) {
                int previous;if(!mrg_read(&p,groups[j-1].setup,0x30,&previous,4))goto done;
                if(previous<=priority)break;groups[j]=groups[j-1];j--;
            }
            groups[j]=value;
        }
        count=3;
    }
    if(!mrg_attached(&p,groups,count))goto done;
    /* Recheck the exact actual binding; lifetime tokens and owned observer
     * readiness are supplied by the enclosing synchronous native boundary. */
    uintptr_t again;
    if(!mrg_read(&p,in->resource,0x60,&again,8))goto done;
    if(again!=model) {mrg_fail(&p,SH_DEFAULT_READ_INVOCATION,model);goto done;}
    if(model) {
        if(!mrg_read(&p,model,0x138,&again,8))goto done;
        if(again!=skeleton) {mrg_fail(&p,SH_DEFAULT_READ_INVOCATION,skeleton);goto done;}
    }
    if(skeleton) {
        if(!mrg_read(&p,skeleton,0x50,&again,8))goto done;
    } else if(!mrg_read(&p,in->resource,0x338,&again,8))goto done;
    if(again!=hybrid) {mrg_fail(&p,SH_DEFAULT_READ_INVOCATION,hybrid);goto done;}
    result=mrg_stable(&p);
done:free(p.spans);free(p.witnesses);return result;
}
