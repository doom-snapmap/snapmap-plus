    memcpy(&list->data,bytes,8);memcpy(&list->count,bytes+8,4);memcpy(&list->capacity,bytes+12,4);
    memcpy(&list->growth,bytes+16,2);list->flags=bytes[19];
    if(list->count<0 || list->capacity<0 || list->count>list->capacity || (list->capacity && !list->data))
        return mrg_fail(p,SH_DEFAULT_READ_OWNERSHIP,at);
    if(stride && (size_t)list->capacity>SIZE_MAX/stride)return mrg_fail(p,SH_DEFAULT_READ_BOUNDS,at);
